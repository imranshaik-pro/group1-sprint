"""Generate the UPSC catalogue from the supplied ZIP; never execute archive content."""
import hashlib, json, pathlib, re, sys, zipfile
from urllib.parse import quote, urlsplit
root=pathlib.Path(__file__).resolve().parents[1]
archive=pathlib.Path(sys.argv[1])
source='https://github.com/madhurimarawat/UPSC-Notes-Resources'
revision='3e9d46ce703ce18b9a161ca4b8819f789f31de46'
def label(s):
    return re.sub(r'\s+', ' ', s.replace('_',' ').replace('-', ' ')).strip()
with zipfile.ZipFile(archive) as z:
    entries=[]
    for info in sorted(z.infolist(), key=lambda i:i.filename):
        if info.is_dir(): continue
        parts=pathlib.PurePosixPath(info.filename).parts
        if len(parts)<2 or parts[0]!='UPSC-Notes-Resources-main' or '..' in parts: raise ValueError('Unexpected archive path')
        path='/'.join(parts[1:]); suffix=pathlib.PurePosixPath(path).suffix.lower()
        if path in ['LICENSE','README.md']: continue
        text=z.read(info).decode('utf-8-sig').strip() if suffix in ['.md','.txt'] else ''
        links=[]
        for url in re.findall(r'https?://[^\s<>\[\]"\)]+',text):
            url=url.rstrip('.,;'); parsed=urlsplit(url)
            if parsed.scheme=='https' and parsed.netloc and not parsed.username and url not in links: links.append(url)
        subject=label(parts[1]) if len(parts)>2 else 'General guidance'
        title=label(pathlib.PurePosixPath(path).stem)
        if title.lower() in ['links','notes link','question paper links']: title=label('/'.join(parts[2:-1]))+' · resources' if len(parts)>3 else subject+' · resources'
        entries.append(dict(id='upsc-'+hashlib.sha256(path.encode()).hexdigest()[:14],subject=subject,title=title,path=path,format=suffix[1:].upper() or 'FILE',bytes=info.file_size,url=source+'/blob/'+revision+'/'+quote(path,safe='/'),text=text,links=links,reviewStatus='unreviewed'))
    data=dict(source=source,revision=revision,archiveSha256=hashlib.sha256(archive.read_bytes()).hexdigest(),license='MIT',copyright='Copyright (c) 2026 Madhurima Rawat',resources=entries)
    out='// Generated by scripts/import-upsc.py. Source attribution: Madhurima Rawat (MIT).\nexport const upscCatalogue = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n'
    for path in ['app/upsc-resources.js','studio/lib/upsc-resources.js']:(root/path).write_text(out)
    (root/'docs/UPSC-SOURCE-LICENSE.txt').write_bytes(z.read('UPSC-Notes-Resources-main/LICENSE'))
print(f'Imported {len(entries)} resources across {len(set(e["subject"] for e in entries))} subjects; {sum(bool(e["text"]) for e in entries)} readable text files.')
